# A One-Way Table in Probability and Statistics is a table that shows the frequency (count) of only one variable.

# It is also called a frequency table.

# Example

# Suppose we collect data about students’ favorite subjects:

# Subject	Number of Students
# Math	        12
# Science	    8
# English	    5
# Computer	    10

# This table contains information about one characteristic only → favorite subject.

# So, it is called a One-Way Table.

