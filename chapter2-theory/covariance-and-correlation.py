# Covariance in Statistics measures how two variables change together.

# It shows whether variables move in:

# the same direction
# or opposite directions

# Meaning
# Positive covariance → both variables increase together
# Negative covariance → one increases while the other decreases
# Zero covariance → no relationship
# Example
# More study hours → higher marks
# (positive covariance)


# Correlation

# Correlation measures both:

# strength
# and direction

# of the relationship between two variables.

# It is a standardized form of covariance


# | Value of (r) | Meaning                      |
# | ------------ | ---------------------------- |
# | (+1)         | Perfect positive correlation |
# | (0)          | No correlation               |
# | (-1)         | Perfect negative correlation |



# | Covariance              | Correlation                    |
# | ----------------------- | ------------------------------ |
# | Shows direction only    | Shows direction and strength   |
# | Value can be any number | Value always between -1 and +1 |
# | Hard to compare         | Easy to compare                |
