# Data Distribution – Point Wise Notes
# Definition
# Data distribution shows how data values are spread.
# It explains the pattern of data.
# Helps understand center, spread, and shape of data.



# Types of Data Distribution
# 1. Normal Distribution
# Bell-shaped curve
# Symmetric distribution
# Mean = Median = Mode
# Most values near center
# Total area under curve = 1

# Examples
# Height
# IQ scores
# Exam marks



# 2. Positively Skewed Distribution
# Right tail is longer
# Most values are smaller
# Mean > Median > Mode

# Examples
# Income
# House prices



# 3. Negatively Skewed Distribution
# Left tail is longer
# Most values are larger
# Mean < Median < Mode


# Examples
# Easy exam scores
# 4. Uniform Distribution
# Equal frequency of values
# Flat-shaped graph


# Examples
# Dice outcomes
# Random numbers
# 5. Bimodal Distribution
# Two peaks (two modes)
# Indicates two groups in data


# Example
# Combined male and female heights



# Important Terms:
# Mean
# Average value
# Median
# Middle value
# Mode
# Most frequent value



# Measures Related to Distribution
# 1. Spread
# Range
# Variance
# Standard deviation


# 2. Shape
# Skewness
# Kurtosis
# Skewness
# Measures asymmetry of data


# Types
# Positive skew
# Negative skew
# Zero skew
# Kurtosis
# Measures peakedness of distribution


# Types

# Leptokurtic → high peak
# Platykurtic → flat peak
# Mesokurtic → normal peak



# Graphs Used:
# Histogram
# Shows frequency distribution

# Box Plot
# Shows spread and outliers

# Density Curve
# Smooth distribution curve

# Frequency Polygon
# Line representation of frequency



# Importance of Data Distribution

# Helps analyze data properly
# Detects outliers
# Used in Machine Learning
# Helps in prediction and decision making


