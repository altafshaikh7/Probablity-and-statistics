# Density Curve in Statistics
# A Density Curve is a smooth curve that represents the distribution of data.

# It shows:
# How data is distributed
# Where values are concentrated
# Probability pattern of data
# The area under the density curve always represents total probability.

# Definition
# A density curve is a smooth graphical representation of a continuous data distribution.

# Main Characteristics of Density Curve
# 1. Smooth Curve
# No sharp edges
# Continuous shape

# 2. Area Under Curve = 1
# Total Area=1
# This means total probability is always 100%.


# 3. Probability Representation
# Higher curve → more data concentration
# Lower curve → fewer data value


# 4. Continuous Data
# Used mainly for continuous variables like:
# Height
# Weight
# Temperature


# Shape of Density Curve
# 1. Symmetric Density Curve
# Left and right sides are equal
# Mean = Median

# 2. Right-Skewed Density Curve
# Tail extends toward right

# 3. Left-Skewed Density Curve
# Tail extends toward left



# Important Properties
# Mean
# Center of density curve.

# Median
# Point dividing area into two equal halves.

# Mode
# Highest point of curve.


# Probability in Density Curve
# Probability is represented by area under curve.

# Formula
# P(a<x<b)=Area under the curve between a and b


# Uses of Density Curve:
# Understanding data distribution
# Probability analysis
# Machine Learning

# Data visualization