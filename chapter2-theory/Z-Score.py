# A Z-Score in Statistics tells how far a data value is from the mean (average) in terms of standard deviations.

# It is also called the Standard Score.

# Why Z-Score is Important
# Helps compare different datasets
# Finds unusual values (outliers)
# Used in normal distribution
# Important in probability and hypothesis testing


# Real-Life Example

# If two students score:

# Student A: 85 in Math
# Student B: 90 in Science

# Direct comparison is difficult because subjects may have different averages.

# Using Z-scores helps determine who performed better relative to their class average.