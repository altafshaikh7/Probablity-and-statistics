# # Measures of Central Tendency

# # Measures of Central Tendency are used to find the central value or average of a dataset.
# # They show where most data values are located.

# # Types of Measures of Central Tendency
# # 1. Mean (Average)

# # The mean is the sum of all observations divided by the total number of observations.

# # Mean = ∑x / n


# # Where:

# # ∑x = sum of all values
# # n = number of values
# # Example

# # Data: 2, 4, 6, 8

# # Mean = (2 + 4 + 6 + 8) / 4 = 20 / 4 = 5

# # Uses
# # Most commonly used average
# # Useful for numerical data




# 2. Median
# The median is the middle value when data is arranged in ascending or descending order.
# Steps


# Arrange data in order


# Find the middle value


# Example 1 (Odd observations)
# Data: 1, 3, 5, 7, 9
# Median = 5
# Example 2 (Even observations)
# Data: 2, 4, 6, 8
# Median = (4 + 6) / 2 = 5
# Uses


# Useful when data has extreme values (outliers)



# 3. Mode
# The mode is the value that occurs most frequently in a dataset.
# Example
# Data: 2, 3, 3, 5, 7
# Mode = 3
# Uses


# Useful for categorical data


# Shows most common observation



