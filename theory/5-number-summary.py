# Five-Number Summary in Statistics
# The Five-Number Summary is a statistical method used to describe a dataset using five important values.
# It helps us understand:


# Center of data


# Spread of data


# Presence of outliers



# The Five Numbers
# The five-number summary consists of:


# Minimum value


# First Quartile (Q₁)


# Median (Q₂)


# Third Quartile (Q₃)


# Maximum value



# Structure of Five-Number Summary
# Minimum, Q1, Median, Q3, Maximum\text{Minimum},\ Q_1,\ \text{Median},\ Q_3,\ \text{Maximum}Minimum, Q1​, Median, Q3​, Maximum

# Meaning of Each Value
# TermMeaningMinimumSmallest valueQ₁25% of data lies below itMedian (Q₂)Middle valueQ₃75% of data lies below itMaximumLargest value

# Steps to Find Five-Number Summary
# Step 1: Arrange Data
# Write data in ascending order.
# Step 2: Find Minimum
# Smallest observation.
# Step 3: Find Median (Q₂)
# Middle value of dataset.
# Step 4: Find Q₁
# Median of lower half of data.
# Step 5: Find Q₃
# Median of upper half of data.
# Step 6: Find Maximum
# Largest observation.

# Example
# Data:
# 2, 4, 6, 8, 10, 12, 14, 16, 18

# Step 1: Minimum
# Minimum = 2

# Step 2: Median (Q₂)
# Middle value = 10

# Step 3: Q₁
# Lower half:
# 2, 4, 6, 8
# Q₁ = (4 + 6)/2 = 5

# Step 4: Q₃
# Upper half:
# 12, 14, 16, 18
# Q₃ = (14 + 16)/2 = 15

# Step 5: Maximum
# Maximum = 18

# Final Five-Number Summary
# MinimumQ₁MedianQ₃Maximum25101518

# Relation with Box Plot
# Five-number summary is used to create a box plot.


# Minimum → left whisker


# Q₁ → left side of box


# Median → line inside box


# Q₃ → right side of box


# Maximum → right whisker



# Finding Outliers Using Five-Number Summary
# First calculate:
# IQR=Q3−Q1IQR=Q_3-Q_1IQR=Q3​−Q1​
# Then calculate limits:
# Lower Limit
# Q1−1.5(IQR)Q_1-1.5(IQR)Q1​−1.5(IQR)
# Upper Limit
# Q3+1.5(IQR)Q_3+1.5(IQR)Q3​+1.5(IQR)
# Values outside these limits are outliers.

# Advantages of Five-Number Summary


# Easy to understand


# Gives quick overview of data


# Helps identify outliers


# Useful for box plots



# Disadvantages


# Does not use all data values


# Less detailed than variance or standard deviation



# Applications
# Data Analysis
# Summarizes datasets quickly.
# Machine Learning
# Used during exploratory data analysis (EDA).
# Business
# Analyzes sales and customer data.
# Research
# Compares datasets easily.

# Important Points


# Five-number summary gives a compact description of data.


# Quartiles divide data into four equal parts.


# It is closely related to IQR and box plots.


# Useful for detecting skewness and outliers.

