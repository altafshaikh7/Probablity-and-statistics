# A Histogram is a graph used in Statistics to represent the frequency distribution of continuous data.

# It uses connected bars to show how data is spread over different intervals (class intervals).

# Example
# Marks	Frequency
# 0–10	5
# 10–20	8
# 20–30	12

# In a histogram:

# X-axis → class intervals
# Y-axis → frequency
# Bars touch each other because data is continuous
# Main Features
# Represents continuous data
# Bars have no gaps
# Shows distribution shape clearly

# Uses
# Understanding data distribution
# Finding patterns and trends
# Statistical analysis