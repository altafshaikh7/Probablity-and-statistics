# Dependent Events

# Dependent Events in Probability and Statistics are events where the occurrence of one event affects the probability of another event.

# In simple words:

# The result of the first event changes the chance of the second event.



# Example

# Suppose a bag contains:

# 3 red balls
# 2 blue balls

# If one ball is taken out without replacement, the total balls change.

# So, the second selection depends on the first selection.



# Key Points
# One event affects another
# Usually occurs without replacement
# Conditional probability is used


# Real-Life Examples
# Drawing cards without replacement
# Selecting students from a group
# Picking balls from a bag without replacement