# A Z-test is a statistical test used to check whether there is a significant difference between:

# a sample mean and population mean, or
# two sample means/proportions

# It is mainly used when:

# sample size is large (n≥30)
# population standard deviation (σ) is known





# Key Points
# Used for large samples
# Uses normal distribution
# Faster and simpler than T-test
# If population SD is unknown and sample is small → use T-test instead