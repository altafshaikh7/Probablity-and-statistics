# | Basis            | Descriptive Statistics         | Inferential Statistics                     |
# | ---------------- | ------------------------------ | ------------------------------------------ |
# | Definition       | Describes and summarizes data  | Makes predictions or conclusions from data |
# | Purpose          | To present data clearly        | To infer about population                  |
# | Focus            | Existing data                  | Future prediction / decision               |
# | Data Used        | Complete collected data        | Sample data                                |
# | Uses Probability | No                             | Yes                                        |
# | Complexity       | Simple                         | More complex                               |
# | Result           | Tables, graphs, averages       | Predictions and hypothesis testing         |
# | Common Methods   | Mean, Median, Mode, Graphs     | Confidence Interval, Hypothesis Testing    |
# | Example          | Finding average marks of class | Predicting performance of all students     |
# | Output           | Description of data            | Conclusion about population                |
