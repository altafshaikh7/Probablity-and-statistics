# Mutually Exclusive Events

# Mutually Exclusive Events in Probability and Statistics are events that cannot occur at the same time.

# If one event happens, the other event cannot happen.


# Example

# When rolling a dice:

# Event A = getting 2
# Event B = getting 5

# A dice cannot show both 2 and 5 together in one roll.

# So, these events are mutually exclusive.


# Key Points
# Cannot happen together
# Intersection probability is zero
# Addition rule is used



# Real-Life Examples
# A person being both alive and dead at the same time
# Tossing a coin and getting both head and tail together
# Choosing a card that is both King and Queen simultaneously